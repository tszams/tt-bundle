        if (!isset($icons[$name])) {
            $name = 'sparkles';
        }
        $s = (int) $size;
        return sprintf(
            '<svg xmlns="http://www.w3.org/2000/svg" width="%1$d" height="%1$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%2$s</svg>',
            $s,
            $icons[$name]
        );
    }

